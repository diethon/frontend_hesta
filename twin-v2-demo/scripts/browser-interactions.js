async (page) => {
  const passed = []
  const check = (condition, message) => { if (!condition) throw new Error(message); passed.push(message) }
  await page.setViewportSize({ width: 1920, height: 1080 })
  await page.goto('http://127.0.0.1:5178/')
  await page.locator('canvas').waitFor()
  await page.locator('.room-label').nth(5).waitFor({ state: 'visible', timeout: 20000 })
  await page.waitForTimeout(1500)
  check(await page.locator('canvas').isVisible(), 'Real WebGL canvas mounted')
  check(await page.locator('.room-label').count() === 6, 'Six 3D room labels visible')
  await page.screenshot({ path: 'output/playwright/desktop-1920.png' })

  await page.getByRole('button', { name: 'Phòng ngủ', exact: true }).click(); await page.waitForTimeout(100)
  await page.waitForTimeout(800)
  check(await page.getByRole('heading', { name: 'Phòng ngủ', exact: true }).isVisible(), 'Room selection updates device panel')
  const focused = await page.locator('canvas').screenshot()
  await page.getByRole('button', { name: 'Đặt lại camera', exact: true }).click(); await page.waitForTimeout(100)
  await page.waitForTimeout(800)
  const reset = await page.locator('canvas').screenshot()
  check(focused.toString('base64') !== reset.toString('base64'), 'Room focus and reset change actual rendered camera')
  await page.getByRole('button', { name: 'Chọn phòng Phòng bếp', exact: true }).click(); await page.waitForTimeout(100)
  check(await page.getByRole('heading', { name: 'Phòng bếp', exact: true }).isVisible(), '3D room label selects kitchen')

  await page.getByRole('button', { name: 'Tầng 2', exact: true }).click(); await page.waitForTimeout(100)
  check(await page.getByRole('heading', { name: 'Sảnh gia đình', exact: true }).isVisible(), 'Second floor updates rooms')
  check(await page.getByRole('slider', { name: 'Độ sáng' }).inputValue() === '50', 'Second floor has its own device scenario')
  await page.getByRole('button', { name: '25%', exact: true }).click(); await page.waitForTimeout(100)
  await page.getByRole('button', { name: 'Tầng 3', exact: true }).click(); await page.waitForTimeout(100)
  check(await page.getByRole('heading', { name: 'Phòng thư giãn', exact: true }).isVisible(), 'Third floor updates rooms')
  check(await page.getByRole('slider', { name: 'Độ sáng' }).inputValue() === '100', 'Third floor state independent')
  await page.waitForTimeout(800)
  await page.screenshot({ path: 'output/playwright/floor-3.png' })
  await page.getByRole('button', { name: 'Tầng 2', exact: true }).click(); await page.waitForTimeout(100)
  check(await page.getByRole('slider', { name: 'Độ sáng' }).inputValue() === '25', 'Returning to a floor preserves its state')
  await page.getByRole('combobox', { name: 'Chọn tầng trong danh sách' }).selectOption('floor-1'); await page.waitForTimeout(100)
  check(await page.getByRole('heading', { name: 'Phòng khách', exact: true }).isVisible(), 'Explorer floor selector works')
  check(await page.getByRole('slider', { name: 'Độ sáng' }).inputValue() === '75', 'Ground floor state remains unchanged')

  await page.getByRole('button', { name: 'Chọn Điều hòa', exact: true }).click(); await page.waitForTimeout(100)
  check(await page.locator('.thermostat').isVisible(), '3D device marker opens AC controls')
  await page.getByRole('button', { name: 'Tăng nhiệt độ', exact: true }).click(); await page.waitForTimeout(100)
  check((await page.locator('.thermostat').innerText()).includes('25'), 'AC temperature updates')
  await page.getByRole('button', { name: 'Hút ẩm', exact: true }).click(); await page.waitForTimeout(100)
  check(await page.getByRole('button', { name: 'Hút ẩm', exact: true }).getAttribute('aria-pressed') === 'true', 'AC mode updates')
  await page.getByRole('switch', { name: 'Bật/tắt Điều hòa', exact: true }).click(); await page.waitForTimeout(100)
  check(await page.getByRole('button', { name: 'Tăng nhiệt độ', exact: true }).isDisabled(), 'AC power disables temperature control')

  await page.getByRole('button', { name: 'Chọn Quạt trần', exact: true }).click(); await page.waitForTimeout(100)
  await page.getByRole('switch', { name: 'Bật/tắt Quạt trần', exact: true }).click(); await page.waitForTimeout(100)
  await page.getByRole('button', { name: 'Mạnh Cấp 3', exact: true }).click(); await page.waitForTimeout(100)
  check(await page.getByRole('button', { name: 'Mạnh Cấp 3', exact: true }).getAttribute('aria-pressed') === 'true', 'Fan power and speed update')
  await page.getByRole('switch', { name: 'Bật/tắt Quạt trần', exact: true }).click(); await page.waitForTimeout(100)

  await page.getByRole('button', { name: 'Chọn Smart TV', exact: true }).click(); await page.waitForTimeout(100)
  check(await page.getByRole('switch', { name: 'Bật/tắt Smart TV', exact: true }).isDisabled(), 'Offline device cannot be controlled')
  await page.getByRole('button', { name: 'Chọn Cảm biến nhiệt độ', exact: true }).click(); await page.waitForTimeout(100)
  check((await page.locator('.sensor-reading').innerText()).includes('26.8'), 'Sensor details display simulated reading')

  await page.getByRole('button', { name: 'Chọn Đèn phòng khách', exact: true }).click(); await page.waitForTimeout(100)
  await page.getByRole('button', { name: 'Chuyển sang ban đêm', exact: true }).click(); await page.waitForTimeout(100)
  await page.waitForTimeout(800)
  check(await page.locator('.scene-stage.night').count() === 1, 'Day/night environment toggles')
  await page.screenshot({ path: 'output/playwright/night.png' })
  const lightOn = await page.locator('canvas').screenshot()
  await page.getByRole('switch', { name: 'Bật/tắt Đèn phòng khách', exact: true }).click(); await page.waitForTimeout(100)
  await page.waitForTimeout(800)
  check(await page.getByRole('slider', { name: 'Độ sáng' }).isDisabled(), 'Light power disables brightness control')
  const lightOff = await page.locator('canvas').screenshot()
  check(lightOn.toString('base64') !== lightOff.toString('base64'), 'Light toggle changes real 3D pixels')
  await page.getByRole('switch', { name: 'Bật/tắt Đèn phòng khách', exact: true }).click(); await page.waitForTimeout(100)
  await page.getByRole('button', { name: '25%', exact: true }).click(); await page.waitForTimeout(100)
  check(await page.getByRole('slider', { name: 'Độ sáng' }).inputValue() === '25', 'Brightness presets update mock state')
  await page.getByRole('button', { name: 'Trắng 6500K', exact: true }).click(); await page.waitForTimeout(100)
  check(await page.getByRole('button', { name: 'Trắng 6500K', exact: true }).getAttribute('aria-pressed') === 'true', 'Color temperature selection works')

  const initialWidth = await page.locator('.scene-stage').evaluate(el => el.clientWidth)
  await page.getByRole('button', { name: 'Thu gọn danh sách phòng', exact: true }).click(); await page.waitForTimeout(100)
  await page.getByRole('button', { name: 'Thu gọn điều khiển thiết bị', exact: true }).click(); await page.waitForTimeout(100)
  const expandedWidth = await page.locator('.scene-stage').evaluate(el => el.clientWidth)
  check(expandedWidth > initialWidth + 350, 'Collapsing panels increases real scene width')
  await page.getByRole('button', { name: 'Chọn Điều hòa', exact: true }).click(); await page.waitForTimeout(100)
  check(await page.locator('.device-panel.collapsed').count() === 0, 'Device marker reopens collapsed controls')
  await page.getByRole('button', { name: 'Mở danh sách phòng', exact: true }).click(); await page.waitForTimeout(100)
  await page.getByRole('button', { name: 'Chuyển sang ban ngày', exact: true }).click(); await page.waitForTimeout(100)
  await page.getByRole('button', { name: 'Đặt lại camera', exact: true }).click(); await page.waitForTimeout(100)
  await page.getByRole('button', { name: 'Phóng to', exact: true }).click(); await page.waitForTimeout(100)
  await page.waitForTimeout(800)
  await page.getByRole('button', { name: 'Thu nhỏ', exact: true }).click(); await page.waitForTimeout(100)
  await page.getByRole('button', { name: 'Xoay mô hình', exact: true }).click(); await page.waitForTimeout(100)
  check(await page.getByRole('button', { name: 'Xoay mô hình', exact: true }).getAttribute('aria-pressed') === 'true', 'Rotate toolbar mode works')
  await page.getByRole('button', { name: 'Di chuyển camera', exact: true }).click(); await page.waitForTimeout(100)
  check(await page.getByRole('button', { name: 'Di chuyển camera', exact: true }).getAttribute('aria-pressed') === 'true', 'Pan toolbar mode works')
  await page.getByRole('button', { name: 'Chọn phòng', exact: true }).click(); await page.waitForTimeout(100)

  await page.getByRole('button', { name: 'Toàn màn hình', exact: true }).click(); await page.waitForTimeout(100)
  check(await page.evaluate(() => !!document.fullscreenElement), 'Fullscreen works')
  await page.getByRole('button', { name: 'Thoát toàn màn hình', exact: true }).click(); await page.waitForTimeout(100)
  await page.getByRole('button', { name: 'Hướng dẫn', exact: true }).click(); await page.waitForTimeout(100)
  check(await page.getByRole('dialog').isVisible(), 'Help dialog opens')
  await page.keyboard.press('Escape')
  check(await page.getByRole('dialog').isVisible() === false, 'Help dialog supports Escape')
  await page.keyboard.press('/')
  check(await page.getByRole('textbox', { name: 'Tìm kiếm phòng' }).evaluate(el => el === document.activeElement), 'Room search keyboard shortcut works')
  await page.getByRole('textbox', { name: 'Tìm kiếm phòng' }).fill('khong-co-phong')
  check(await page.getByText('Không tìm thấy phòng.').isVisible(), 'Room search empty state works')
  await page.getByRole('button', { name: 'Xóa tìm kiếm', exact: true }).click(); await page.waitForTimeout(100)
  return { passed, total: passed.length }
}
