async (page) => {
  const results = []
  const errors = []
  const apiRequests = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('request', request => { if (/\/(?:api|mqtt|auth|stomp|sockjs)\b/i.test(request.url())) apiRequests.push(request.url()) })
  await page.goto('http://127.0.0.1:5178/')
  await page.locator('canvas').waitFor()
  await page.locator('.room-label').nth(5).waitFor({ state: 'visible', timeout: 20000 })
  await page.waitForTimeout(1000)
  for (const size of [{ width: 1920, height: 1080 }, { width: 1440, height: 900 }, { width: 390, height: 844 }, { width: 320, height: 740 }]) {
    await page.setViewportSize(size)
    await page.getByRole('button', { name: 'Đặt lại camera', exact: true }).click()
    await page.waitForTimeout(800)
    const layout = await page.evaluate(() => {
      const stage = document.querySelector('.scene-stage').getBoundingClientRect()
      const textOverflow = [...document.querySelectorAll('.room-copy strong, .device-row strong, .metric-title, .selected-room h2')].filter(el => el.clientWidth > 0 && el.scrollWidth > el.clientWidth + 1).map(el => el.textContent)
      return { viewport: innerWidth, pageWidth: document.documentElement.scrollWidth, scene: { x: Math.round(stage.x), y: Math.round(stage.y), width: Math.round(stage.width), height: Math.round(stage.height) }, textOverflow }
    })
    if (layout.pageWidth > size.width) throw new Error('Horizontal overflow at ' + size.width + ': ' + layout.pageWidth)
    if (layout.textOverflow.length) throw new Error('Text overflow at ' + size.width + ': ' + layout.textOverflow.join(', '))
    await page.screenshot({ path: 'output/playwright/desktop-' + size.width + '.png', fullPage: size.width < 600 })
    results.push(layout)
  }
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.getByRole('button', { name: 'Thu gọn danh sách phòng', exact: true }).click()
  await page.getByRole('button', { name: 'Thu gọn điều khiển thiết bị', exact: true }).click()
  await page.getByRole('button', { name: 'Đặt lại camera', exact: true }).click()
  await page.waitForTimeout(800)
  await page.screenshot({ path: 'output/playwright/expanded-1440.png' })
  const canvas = page.locator('canvas')
  const box = await canvas.boundingBox()
  const before = await canvas.screenshot()
  await page.getByRole('button', { name: 'Xoay mô hình', exact: true }).click()
  await page.mouse.move(box.x + box.width * .5, box.y + box.height * .55)
  await page.mouse.down()
  await page.mouse.move(box.x + box.width * .65, box.y + box.height * .55, { steps: 16 })
  await page.mouse.up()
  await page.waitForTimeout(800)
  const rotated = await canvas.screenshot()
  if (before.toString('base64') === rotated.toString('base64')) throw new Error('Drag rotation did not change the model')
  await page.getByRole('button', { name: 'Di chuyển camera', exact: true }).click()
  await page.mouse.move(box.x + box.width * .5, box.y + box.height * .5)
  await page.mouse.down()
  await page.mouse.move(box.x + box.width * .55, box.y + box.height * .55, { steps: 12 })
  await page.mouse.up()
  await page.waitForTimeout(600)
  const panned = await canvas.screenshot()
  if (rotated.toString('base64') === panned.toString('base64')) throw new Error('Pan did not move camera')
  await page.mouse.wheel(0, -200)
  await page.waitForTimeout(600)
  const zoomed = await canvas.screenshot()
  if (panned.toString('base64') === zoomed.toString('base64')) throw new Error('Wheel zoom did not change camera')
  await page.getByRole('button', { name: 'Đặt lại camera', exact: true }).click()
  await page.getByRole('button', { name: 'Chọn phòng', exact: true }).click()
  await page.waitForTimeout(800)
  // The accessible room label exposes the projected room location; offset onto real floor geometry.
  const kitchen = await page.getByRole('button', { name: 'Chọn phòng Phòng bếp', exact: true }).boundingBox()
  await page.mouse.dblclick(kitchen.x + kitchen.width * .5, kitchen.y - 28, { delay: 80 })
  await page.waitForTimeout(800)
  if (!(await page.locator('[role=status]').innerText()).includes('phòng bếp')) throw new Error('Direct 3D floor picking failed')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.getByRole('button', { name: 'Đặt lại camera', exact: true }).click()
  await page.waitForTimeout(100)
  const reduced = await page.locator('.room-label.selected').boundingBox()
  await page.waitForTimeout(250)
  const stable = await page.locator('.room-label.selected').boundingBox()
  // The projected room anchor isolates camera motion from lamp fade-in when
  // leaving the room cutaway and remounting the other rooms' light fixtures.
  if (!reduced || !stable || Math.hypot(reduced.x - stable.x, reduced.y - stable.y) > .5) throw new Error('Reduced motion camera is not immediately stable')
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.setViewportSize({ width: 1920, height: 1080 })
  await page.getByRole('button', { name: 'Mở danh sách phòng', exact: true }).click()
  await page.getByRole('button', { name: 'Mở điều khiển thiết bị', exact: true }).click()
  await page.getByRole('button', { name: 'Đặt lại camera', exact: true }).click()
  await page.waitForTimeout(800)
  if (errors.length || apiRequests.length) throw new Error(JSON.stringify({ errors, apiRequests }))
  return { results, errors, apiRequests, realCameraInteraction: ['drag rotate', 'drag pan', 'wheel zoom', 'double-click real floor', 'reduced motion'] }
}
